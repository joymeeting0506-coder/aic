#!/usr/bin/env python3
"""Augment real, hand-labeled Gazebo images ONLY AFTER session-disjoint train/val split.

Works on an existing YOLO dataset generated by split.py. Never modifies validation.
Only generates photometric augmentations: bboxes do not move.
"""
import argparse
import random
from pathlib import Path
import cv2
import numpy as np

ap=argparse.ArgumentParser(description=__doc__)
ap.add_argument('--dataset',type=Path,default=Path.home()/'aic_ws/plate_yolo_work/dataset_real')
ap.add_argument('--copies',type=int,default=5)
ap.add_argument('--seed',type=int,default=42)
a=ap.parse_args()
if a.copies<0 or a.copies>100: ap.error('copies must be between 0 and 100')
base=a.dataset.expanduser()
train_img=base/'images/train';train_lab=base/'labels/train'
if not train_img.is_dir() or not train_lab.is_dir(): ap.error('Missing train images and labels (run split.py first)')
imgs=[p for p in sorted(train_img.iterdir()) if p.suffix.lower() in {'.jpg','.png','.jpeg'} and not p.stem.startswith('aug_')]
if not imgs:ap.error('No train images')
rng=random.Random(a.seed)
n=0
for src in imgs:
    label=train_lab/(src.stem+'.txt')
    if not label.exists(): continue
    frame=cv2.imread(str(src))
    if frame is None:continue
    for i in range(a.copies):
        out=frame.copy()
        out=cv2.convertScaleAbs(out,alpha=rng.uniform(.68,1.27),beta=rng.uniform(-18,16))
        if rng.random()<.7:
            k=rng.choice([3,5]);out=cv2.GaussianBlur(out,(k,k),rng.uniform(.2,1.25))
        if rng.random()<.3:
            noise=np.random.default_rng(rng.randint(0,2**32-1)).normal(0,rng.uniform(1,7),out.shape)
            out=np.clip(out.astype(np.float32)+noise,0,255).astype('uint8')
        target='aug_'+src.stem+f'_{i:02d}'
        image_dest=train_img/(target+'.jpg')
        label_dest=train_lab/(target+'.txt')
        if image_dest.exists() or label_dest.exists():
            ap.error('Augment output exists; abort to avoid overwriting: '+str(image_dest))
        cv2.imwrite(str(image_dest),out,[cv2.IMWRITE_JPEG_QUALITY,rng.randint(72,96)])
        label_dest.write_bytes(label.read_bytes())
        n+=1
print(f'OK: added {n} real-image training augmentations; validation untouched, bboxes unchanged.')
